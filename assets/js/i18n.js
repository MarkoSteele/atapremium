class AtaI18n {
    constructor() {
        this.currentLang = localStorage.getItem('ata_premium_lang') || 'pt';
        this.supportedLangs = ['pt', 'en', 'es'];
        if (!this.supportedLangs.includes(this.currentLang)) {
            this.currentLang = 'pt';
        }
        this.init();
    }

    init() {
        const bootstrap = () => {
            this.renderLanguageSwitchers();
            this.bindEvents();
            if (this.currentLang !== 'pt') {
                this.setLanguage(this.currentLang, false);
            }
        };

        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', bootstrap);
        } else {
            bootstrap();
        }
    }

    renderLanguageSwitchers() {
        // Desktop Switcher
        const desktopMount = document.querySelector('.header-lang-mount');
        if (desktopMount) {
            desktopMount.innerHTML = `
                <div class="lang-switcher-dropdown" id="langSwitcherDropdown">
                    <button type="button" class="lang-btn-current" aria-haspopup="true" aria-expanded="false" aria-label="Alterar Idioma">
                        <span class="lang-flag-wrap">${ATA_FLAGS[this.currentLang]}</span>
                        <span class="lang-code-current">${this.currentLang.toUpperCase()}</span>
                        <svg class="lang-chevron" viewBox="0 0 24 24" width="12" height="12" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><polyline points="6 9 12 15 18 9"></polyline></svg>
                    </button>
                    <div class="lang-dropdown-menu" role="menu">
                        <button type="button" class="lang-option ${this.currentLang === 'pt' ? 'is-active' : ''}" data-lang="pt" role="menuitem">
                            <span class="lang-flag-wrap">${ATA_FLAGS.pt}</span>
                            <span class="lang-name">Português</span>
                            <span class="lang-check">✓</span>
                        </button>
                        <button type="button" class="lang-option ${this.currentLang === 'en' ? 'is-active' : ''}" data-lang="en" role="menuitem">
                            <span class="lang-flag-wrap">${ATA_FLAGS.en}</span>
                            <span class="lang-name">English</span>
                            <span class="lang-check">✓</span>
                        </button>
                        <button type="button" class="lang-option ${this.currentLang === 'es' ? 'is-active' : ''}" data-lang="es" role="menuitem">
                            <span class="lang-flag-wrap">${ATA_FLAGS.es}</span>
                            <span class="lang-name">Español</span>
                            <span class="lang-check">✓</span>
                        </button>
                    </div>
                </div>
            `;
        }

        // Mobile Switcher
        const mobileMount = document.querySelector('.mobile-lang-mount');
        if (mobileMount) {
            mobileMount.innerHTML = `
                <div class="mobile-lang-segmented" role="radiogroup" aria-label="Seleção de Idioma">
                    <button type="button" class="mobile-lang-tab ${this.currentLang === 'pt' ? 'is-active' : ''}" data-lang="pt">
                        <span class="lang-flag-wrap">${ATA_FLAGS.pt}</span>
                        <span>PT</span>
                    </button>
                    <button type="button" class="mobile-lang-tab ${this.currentLang === 'en' ? 'is-active' : ''}" data-lang="en">
                        <span class="lang-flag-wrap">${ATA_FLAGS.en}</span>
                        <span>EN</span>
                    </button>
                    <button type="button" class="mobile-lang-tab ${this.currentLang === 'es' ? 'is-active' : ''}" data-lang="es">
                        <span class="lang-flag-wrap">${ATA_FLAGS.es}</span>
                        <span>ES</span>
                    </button>
                </div>
            `;
        }
    }

    bindEvents() {
        // Toggle Desktop Dropdown & Troca de Idioma com deleção global robusta
        document.addEventListener('click', (e) => {
            const btn = e.target.closest('.lang-btn-current');
            const option = e.target.closest('.lang-option, .mobile-lang-tab');
            const dropdown = document.querySelector('#langSwitcherDropdown');

            if (btn) {
                e.preventDefault();
                e.stopPropagation();
                const parentDropdown = btn.closest('.lang-switcher-dropdown') || dropdown;
                if (parentDropdown) {
                    const isOpen = parentDropdown.classList.contains('is-open');
                    parentDropdown.classList.toggle('is-open', !isOpen);
                    btn.setAttribute('aria-expanded', String(!isOpen));
                }
                return;
            }

            if (option) {
                e.preventDefault();
                e.stopPropagation();
                const targetLang = option.getAttribute('data-lang');
                if (targetLang && this.supportedLangs.includes(targetLang)) {
                    this.setLanguage(targetLang, true);
                    if (dropdown) dropdown.classList.remove('is-open');
                }
                return;
            }

            if (dropdown && !dropdown.contains(e.target)) {
                dropdown.classList.remove('is-open');
                const toggleBtn = dropdown.querySelector('.lang-btn-current');
                if (toggleBtn) toggleBtn.setAttribute('aria-expanded', 'false');
            }
        });
    }

    setLanguage(lang, triggerTracking = true) {
        if (!this.supportedLangs.includes(lang)) return;
        this.currentLang = lang;
        localStorage.setItem('ata_premium_lang', lang);
        document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;

        const translations = ATA_TRANSLATIONS[lang] || ATA_TRANSLATIONS.pt;

        // Atualiza textos marcados com data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[key] !== undefined) {
                if (el.tagName === 'OPTION') {
                    el.textContent = translations[key];
                } else {
                    el.innerHTML = translations[key];
                }
            }
        });

        // Atualiza placeholders
        document.querySelectorAll('[data-i18n-ph]').forEach(el => {
            const key = el.getAttribute('data-i18n-ph');
            if (translations[key] !== undefined) {
                el.setAttribute('placeholder', translations[key]);
            }
        });

        // Atualiza botões e UI do seletor
        this.renderLanguageSwitchers();

        // Reexecuta animação de contagem dos Big Numbers no novo idioma
        if (window.triggerMetricsAnimation) {
            window.triggerMetricsAnimation();
        }

        // Disparo para GTM / DataLayer
        if (triggerTracking && window.dataLayer) {
            window.dataLayer.push({
                event: 'change_language',
                selected_language: lang
            });
        }
    }
}

// Instancia global
window.ataI18n = new AtaI18n();
